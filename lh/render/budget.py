"""reports/page_budget.md: pages per section and part of the full book (from the \\budget labels in the LaTeX .aux),
attribution counts, and estimated savings of compaction options (not applied). Written by `python -m lh book`."""
from __future__ import annotations

import collections
import datetime
import re

from lh.config import BUILD, REPORTS
from lh.model.canon import fold, plain_text

SECTION_NAMES = {"saints": "1 Proper of Saints", "commons": "2 Commons (+ Office for the Dead, BVM on Saturday)",
                 "ordinary": "3 Ordinary (incl. Compline cycle)", "time": "4 Proper of Time", "hymns": "5 Hymns",
                 "psalter": "6–9 Psalter and Canticles", "readings": "10 Office of Readings readings",
                 "other": "Other texts (fallback)", "indexes": "Indexes"}
PART_NAMES = {"commons/commons": "the ten Commons with seasonal forms", "commons/additional":
              "Office for the Dead, Saturday memorial of the BVM", "time/grid": "four-week grid (28 days, all seasons)",
              "time/otweeks": "Ordinary Time: weekly propers (Sunday antiphons A/B/C, collects)",
              "time/proper": "wholly proper days (17–24 Dec, Christmas, Ash Wed, Holy Week, Triduum, Easter Octave, "
                             "Ascension, Pentecost, solemnities of the Lord)",
              "psalter/psalms": "150 psalms", "psalter/canticles": "canticles"}



def aux_labels(name: str = "book") -> dict[str, int]:
    aux = (BUILD / "latex" / f"{name}.aux").read_text(encoding="utf-8", errors="replace")
    out = {}
    for m in re.finditer(r"\\newlabel\{budget:([^}]*)\}\{\{[^}]*\}\{(\d+)\}", aux):
        out[m.group(1)] = int(m.group(2))
    return out


def pdf_pages(name: str = "book") -> int:
    import pymupdf
    from lh.config import BOOK
    return pymupdf.open(BOOK / "out" / f"{name}.pdf").page_count


def norm_alleluia(t: str) -> str:
    t = fold(t)
    t = re.sub(r"\balleluia\b", " ", t)
    return re.sub(r"[^a-z]+", "", t)


def write_budget(book, timings: dict, name: str = "book") -> str:
    labels = aux_labels(name)
    total = pdf_pages(name)
    marks = sorted(labels.items(), key=lambda kv: (kv[1], list(labels).index(kv[0])))
    end = labels.get("end", max(labels.values()) if labels else 0)
    # pages of each marker = next marker's page − own page (the last runs to the end marker, inclusive)
    pages = {}
    for i, (k, p) in enumerate(marks):
        if k == "end":
            continue
        nxt = marks[i + 1][1] if i + 1 < len(marks) else end + 1
        if marks[i + 1][0] == "end" if i + 1 < len(marks) else False:
            nxt = end + 1
        pages[k] = nxt - p
    sections = collections.OrderedDict()
    for k, p in marks:
        if k == "end":
            continue
        sec = k.split("/")[0]
        sections.setdefault(sec, 0)
        sections[sec] += pages[k]
    main = sum(sections.values())
    front = total - main
    readings = sections.get("readings", 0)
    # ---------------------------------------------------------------- attribution counts
    objs = book.objs
    printed_by = collections.Counter(o.home for o in objs.values() if o.id in book.printed)
    # alleluia variants: printed texts that equal another printed text of the same type but for "alleluia"
    base = collections.defaultdict(set)
    for o in objs.values():
        if o.id in book.printed and o.type not in ("psalm", "canticle", "hymn", "reading"):
            t = plain_text(o.type, o.payload)
            if "allel" not in fold(t):
                base[o.type].add(norm_alleluia(t))
    allel = collections.Counter()
    allel_n = collections.Counter()
    for o in objs.values():
        if o.id in book.printed and o.type not in ("psalm", "canticle", "hymn", "reading"):
            t = plain_text(o.type, o.payload)
            if "allel" in fold(t) and norm_alleluia(t) and norm_alleluia(t) in base[o.type]:
                allel[o.home] += -(-(len(t) + 15) // 72) + 0.3     # lines: ~72 characters per line, +0.3 spacing
                allel_n[o.home] += 1
    allel_pages = {s: allel[s] / 44 for s in allel}          # 44 lines of 10 pt per page
    st = book.stats
    att = book.db.c.execute("SELECT kind, count(*) FROM reference GROUP BY kind").fetchall()
    kinds = {r[0]: r[1] for r in att}
    from lh.model.attribute import content
    uses = sum(len(content(occs)) for occs in book.db._occ.values())     # printed texts, repeats of antiphons excluded
    n_printed = len(book.printed)
    lines = [
        "# Page budget of the full book",
        "",
        f"Generated by `python -m lh book` ({datetime.date.today().isoformat()}) from `build/latex/{name}.aux` "
        "(`\\budget` labels) and the PDF. Trim 6 × 9.25 in, body 10 pt EB Garamond. Do not edit by hand.",
        "",
        "## Pages per section (book order)",
        "",
        "| Section | Pages | Share |",
        "|---|---:|---:|",
    ]
    for sec, p in sections.items():
        lines.append(f"| {SECTION_NAMES.get(sec, sec)} | {p:,} | {100 * p / max(main, 1):.0f} % |")
    lines += [f"| Front matter (title, contents) | {front:,} | |",
              f"| **Total** | **{total:,}** | |",
              f"| **Total without the Office of Readings readings** | **{total - readings:,}** | |", "",
              "## Parts", "", "| Part | Pages |", "|---|---:|"]
    for k, p in marks:
        if "/" in k:
            lines.append(f"| {SECTION_NAMES.get(k.split('/')[0], k)}: {PART_NAMES.get(k, k)} | {pages[k]:,} |")
    lines += ["", "Section title pages are counted in the section totals, not in the parts.", "",
              "## Attribution (every text printed once)", "",
              f"- Objects printed in full: **{n_printed:,}** "
              f"({', '.join(f'{k} {v:,}' for k, v in sorted(printed_by.items(), key=lambda kv: -kv[1]))}); "
              f"printing variants of a psalm, canticle or Te Deum given once with the consensus text: "
              f"{len(book.aliases):,}.",
              f"- Printings of these texts in the eight source volumes: {uses:,} (repeated antiphons not counted). "
              f"In the book: {n_printed:,} printed in full, every other use is a page reference "
              f"({st.get('refs', 0):,} references printed) or is absorbed: identical printings in the duplicate copies "
              f"and seasonal grid days share one line, and a whole Compline or \"Omnia de Communi\" hour is one line.",
              f"- Named references (table `reference`): de Communi {kinds.get('de_communi', 0):,} "
              f"(printed {st.get('de_communi', 0):,}; \"Omnia de Communi\" hours: {st.get('omnia_de_communi', 0):,}), "
              f"psalmi de feria {kinds.get('de_feria', 0):,}, seasonal texts covered by the Per annum grid "
              f"{kinds.get('grid', 0):,}.",
              f"- Compline hours given as \"as in the Ordinary\": {st.get('compline_as_form', 0):,}; texts printed by the "
              f"end-of-part fallback (should be 0): {st.get('flushed', 0):,} at their location, "
              f"{st.get('unprinted_fallback', 0):,} in \"Other texts\".",
              "",
              "## Build time", "",
              f"- Generating the LaTeX: {timings.get('generate', 0):.0f} s; LuaLaTeX (latexmk, all passes): "
              f"{timings.get('latex', 0):.0f} s ({timings.get('latex', 0) / 60:.1f} min).",
              "",
              "## Compaction options (estimates, not applied)", "",
              "Line estimate: ~72 characters per line, 44 lines per page (10 pt on the 4.15 × 7.75 in text block).", "",
              "| Option | Estimated saving | Notes |", "|---|---:|---|"]
    a_tot = sum(allel_pages.values())
    lines.append(f"| Easter alleluia variants as a rule (\"in Eastertide add *allelúia*\") instead of printing "
                 f"them in full | ≈ {a_tot:,.0f} pp | {sum(allel_n.values()):,} printed texts differ from another "
                 f"printed text only by *allelúia* ("
                 + ", ".join(f"{SECTION_NAMES[s].split(' ', 1)[1]} {allel_n[s]:,} ≈ {allel_pages.get(s, 0):.0f} pp"
                             for s in sorted(allel_n, key=lambda s: -allel_n[s]))
                 + "). GILH 120: alleluia is added in Eastertide unless it conflicts with the sense. |")
    lines.append(f"| Smaller type for the readings (9 pt instead of 10 pt) | ≈ {readings * 0.19:,.0f} pp | "
                 f"area scales with the square of the size: (9/10)² ≈ 0.81 of {readings:,} pp |")
    lines.append(f"| Smaller type for the readings (8.5 pt) | ≈ {readings * 0.28:,.0f} pp | (8.5/10)² ≈ 0.72 |")
    lines.append(f"| Companion volume for the Office of Readings readings (Readings ribbon) | {readings:,} pp | main volume "
                 f"{total - readings:,} pp; R page references at the Office of Readings would point into the "
                 f"companion volume |")
    lines += ["", "## For the owner to decide (B-12)", "",
              f"- One volume of {total:,} pages at this trim size is far thicker than a usual single-volume "
              "breviary; each volume of the four-volume Liturgia Horarum is of the order of 1,500–2,000 pages on "
              f"bible paper. Without the readings the main volume would have {total - readings:,} pages.",
              "- Options above can be combined; the alleluia rule changes the text as printed (a rubric replaces "
              "printed variants) and needs a decision on how the rule is worded.", ""]
    path = REPORTS / "page_budget.md"
    path.write_text("\n".join(lines), encoding="utf-8")
    return str(path)
