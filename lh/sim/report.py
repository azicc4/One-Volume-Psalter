"""reports/simulation.md: what the simulated readers did, where the time goes, and what would make the book faster to
use. Written by `python -m lh simulate` from the run's own data (build/sim/)."""
from __future__ import annotations

import collections
import datetime as dt
import gzip
import json
import statistics

from lh.config import REPORTS
from lh.sim.reader import COST, SCHEMES, Reader, ribbon_names

SCHEME = "by_use"                     # the book's ribbon scheme (B-16)
HOUR_NAME = {"INV": "Invitatory", "OR": "Office of Readings", "LAUDS": "Lauds", "MIDDAY": "Daytime Prayer (Sext)",
             "VESPERS": "Vespers", "V1": "First Vespers", "V2": "Second Vespers", "COMPLINE": "Compline",
             "COMPLINE1": "Compline after First Vespers"}


def table(head: list[str], rows: list[list]) -> list[str]:
    out = ["| " + " | ".join(head) + " |", "|" + "|".join("---" if i == 0 else "---:" for i in range(len(head))) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return out


def f1(x):
    return f"{x:.1f}"


def m(rs, k):
    return statistics.mean(r[k] for r in rs)


def write_report(sim, trial_rows, rows, exp, prof, timing) -> str:
    from lh.sim.run import OUT
    L = sim.L
    names = ribbon_names(SCHEME)
    from lh.config import VARIANTS
    variant = timing.get("variant", "main")
    v = VARIANTS[variant]
    flag = "" if variant == "main" else f" --variant {variant}"
    md = ["# Simulated use of the book: page turns and ribbons"
          + ("" if variant == "main" else f" ({v['label'].lower()}: {v['file']}.pdf)"), "",
          f"Generated by `python -m lh simulate{flag}` on {dt.date.today().isoformat()} from the book as built "
          f"(`{v['file']}.pdf`, {L.n:,} pages) and the database. Do not edit: re-run the command."]
    if v.get("note"):
        md += ["", f"**{v['note']}.**"]
    md += [""]

    # ------------------------------------------------------------------ method
    md += ["## What was simulated", "",
           "**The book as printed now:**",
           "- the **Ordinary card** (`book/out/card.pdf`, B-14) is in hand, so its texts need no page;",
           "- each **Compline form is printed whole** (B-15);",
           "- the **ribbons are assigned by use** (B-16): " + "; ".join(n for _, n, _ in SCHEMES[SCHEME]) + ".",
           "",
           "**The hours.** Each day the reader says:",
           "- the Invitatory;",
           "- the Office of Readings;",
           "- Lauds;",
           "- Daytime Prayer (Sext);",
           "- Vespers, which is First Vespers of the next day when that day is a Sunday or a solemnity;",
           "- Compline.",
           "",
           "**Where each text comes from.**",
           "- Every text is found on the page it is printed on, via the LaTeX labels of the last build.",
           "- Invisible labels give where each hour begins (`hh:`) and where a text is printed again "
           "(`cp:`, as in whole Compline).",
           "- Each hour starts at its heading, then every text is visited in order.",
           "- Memorials take the weekday's psalms; feasts fill gaps from their Common.",
           "",
           "**The calendar** is the General Roman Calendar (`lh/sim/calendar.py`), simplified:",
           "- universal dates (Epiphany on 6 January, Ascension and Corpus Christi on Thursday);",
           "- no transfers;",
           "- obligatory memorials only (optional ones in one variant run).",
           "",
           "**Each change of spread is classified as:**",
           f"- **turn**: to the next or previous spread (~{COST['turn']} s);",
           f"- **ribbon**: opening at a ribbon (~{COST['ribbon']} s);",
           f"- **look-up**: finding the page by its number (~{COST['search']} s).",
           "",
           f"**Laying a ribbon** costs ~{COST['lay']} s. These times are rough guesses; the counts are the result.",
           "",
           "**Ribbon policies:**",
           "- *by use* and *by section*: each ribbon keeps a part of the book. The reader moves a part's ribbon "
           "to a new place only if that place will be needed again, today or tomorrow, before the place it marks "
           "now.",
           "- *free*: any ribbon goes anywhere, by the best possible rule (Belady). This is the best these ribbons "
           "can do.",
           "- *none*: no ribbons at all.",
           "",
           "Ribbons stay where they are from one day to the next.", ""]

    # ------------------------------------------------------------------ timing
    md += ["## Runs and timing", "",
           "**Phase 1 (trial):** 10 random days, timed.",
           f"- {timing['per_day_ms']:.0f} ms per simulated day.",
           f"- {timing['init']:.0f} s of setup.",
           "",
           f"**Phase 2:** every day of {timing['years']} consecutive liturgical years from Advent 2026 (a full "
           "cycle of weekdays against dates).",
           f"- {timing['phase2_days']:,} simulated days in {timing['phase2_min']:.1f} min.",
           "",
           f"**Phase 3:** {len(exp)} experiments in {timing['phase3_min']:.1f} min.",
           "",
           f"**Phase 4:** {len(prof)} reader-profile runs in {timing['phase4_min']:.1f} min.",
           "",
           f"**Total:** {timing['total_min']:.1f} min of a {timing['budget_min']:.0f}-min budget. Every planned "
           "run finished.", ""]
    md += ["### Phase 1: the ten trial days", ""]
    md += table(["Date", "Office", "Kind", "Steps", "Moves", "Look-ups", "Ribbon jumps", "Turns", "Ribbons laid",
                 "Handling"],
                [[r["date"], r["office"], r["kind"], r["steps"], r["moves"], r["search"], r["ribbon"], r["turn"],
                  r["lay"], f"{r['seconds'] / 60:.1f} min"] for r in trial_rows]) + [""]

    # ------------------------------------------------------------------ the book as printed
    by = collections.defaultdict(list)
    for r in rows:
        if r["tag"] != "trial":
            by[r["tag"]].append(r)
    tag_name = {"roles": "ribbons by use (the book's scheme)", "free": "free (best case for these ribbons)",
                "none": "no ribbons", "roles+optional": "ribbons by use, optional memorials kept"}
    md += ["## The book as printed", "", "### Per day, by ribbon policy", ""]
    md += table(["Ribbon policy", "Days", "Moves", "Look-ups", "Ribbon jumps", "Turns", "Ribbons laid",
                 "Handling per day"],
                [[tag_name.get(t, t), len(rs), f1(m(rs, "moves")), f1(m(rs, "search")), f1(m(rs, "ribbon")),
                  f1(m(rs, "turn")), f1(m(rs, "lay")), f"{m(rs, 'seconds') / 60:.1f} min"] for t, rs in by.items()])
    base = by["roles"]
    md += ["", "### Per hour", ""]
    hrs = collections.defaultdict(collections.Counter)
    for r in base:
        for h, c in r["hours"].items():
            hrs[h].update(c)
            hrs[h]["n"] += 1
    md += table(["Hour", "Days said", "Steps", "Moves", "Look-ups", "Ribbon jumps", "Ribbons laid", "Handling"],
                [[HOUR_NAME.get(h, h), c["n"], f1(c["steps"] / c["n"]), f1(c["moves"] / c["n"]),
                  f1(c["search"] / c["n"]), f1(c["ribbon"] / c["n"]), f1(c["lay"] / c["n"]),
                  f"{c['seconds'] / c['n']:.0f} s"]
                 for h, c in sorted(hrs.items(), key=lambda kv: list(HOUR_NAME).index(kv[0]))])
    md += ["", "### By kind of day", ""]
    kinds = collections.defaultdict(list)
    for r in base:
        kinds[r["kind"]].append(r)
    md += table(["Kind of day", "Days", "Look-ups", "Moves", "Handling"],
                [[k, len(rs), f1(m(rs, "search")), f1(m(rs, "moves")), f"{m(rs, 'seconds') / 60:.1f} min"]
                 for k, rs in sorted(kinds.items(), key=lambda kv: -len(kv[1]))])

    searches, pairs = collections.Counter(), collections.Counter()
    jumps, lays = collections.Counter(), collections.Counter()
    with gzip.open(OUT / "events.jsonl.gz", "rt", encoding="utf-8") as f:
        prev = {}
        for line in f:
            e = json.loads(line)
            if e["tag"] != "roles":
                continue
            if e["action"] == "search":
                searches[(e["slot"], e["section"])] += 1
            if e["action"] != "stay":
                key = (e["date"], e["hour"])
                if key in prev:
                    pairs[(prev[key], e["section"])] += 1
                prev[key] = e["section"]
            if e["action"] == "ribbon":
                jumps[e["ribbon"]] += 1
            if e.get("laid"):
                lays[e["laid"]] += 1
    n = len(base)
    md += ["", "### Where the look-ups come from (per day)", ""]
    md += table(["Text", "Section", "Look-ups per day"],
                [[slot, sec, f"{c / n:.2f}"] for (slot, sec), c in searches.most_common(14)])
    md += ["", "### Which parts of the book the reader moves between (per day)", ""]
    md += table(["From", "To", "Moves per day"], [[a, b, f"{c / n:.1f}"] for (a, b), c in pairs.most_common(10)])
    md += ["", "### The ribbons (per day)", ""]
    md += table(["Ribbon", "Opened at", "Moved"], [[names[r], f"{jumps[r] / n:.2f}", f"{lays[r] / n:.2f}"]
                                                   for r, _, _ in SCHEMES[SCHEME]])

    # ------------------------------------------------------------------ experiments
    b0 = exp[0]
    md += ["", "## Experiments", "",
           f"The same {b0['days']:,} days, each variant turned through by the same reader.",
           "- Rows starting \"+\" add a change to the book as printed.",
           "- Extra pages are estimated from the length of every text printed again in a new place.",
           "- The cycle-order Psalter only reorders what is printed, so it adds no text.", ""]
    md += table(["Variant", "Look-ups", "Moves", "Handling per day", "Saved per day", "Saved", "Extra pages"],
                [[e["name"], f1(e["search"]), f1(e["moves"]), f"{e['seconds'] / 60:.1f} min",
                  f"{(b0['seconds'] - e['seconds']) / 60:.1f} min",
                  f"{100 * (b0['seconds'] - e['seconds']) / b0['seconds']:.0f} %", f"+{e['extra_pages']}"]
                 for e in exp])
    if prof:
        md += ["", "### Reader profiles", ""]
        md += table(["Hours prayed", "Layout", "Look-ups", "Moves", "Handling per day"],
                    [[p["profile"], p["layout"], f1(p["search"]), f1(p["moves"]), f"{p['seconds'] / 60:.1f} min"]
                     for p in prof])
    md += [""] + proposals(exp, b0) + sample(sim, L, trial_rows)
    md += ["## Files", "",
           "- `build/sim/days.jsonl`: one summary per simulated day and run.",
           "- `build/sim/events.jsonl.gz`: every page move and ribbon movement of the phase 2 runs.",
           "- `build/sim/experiments.jsonl` and `build/sim/profiles.jsonl`: the phase 3 and phase 4 results.",
           "- **Code:** `lh/sim/` (calendar, layout, office, reader, whatif, run, report).", ""]
    variant = timing.get("variant", "main")
    path = REPORTS / ("simulation.md" if variant == "main" else f"simulation-{variant}.md")
    path.write_text("\n".join(md), encoding="utf-8")
    return str(path)


def proposals(exp, b0) -> list[str]:
    def find(prefix):
        return next((e for e in exp if e["name"].startswith(prefix)), None)

    def saved(e):
        return f"{(b0['seconds'] - e['seconds']) / 60:.1f} min ({100 * (b0['seconds'] - e['seconds']) / b0['seconds']:.0f} %)"

    old, section, free = find("without the card, ribbons by section"), find("the same, ribbons by section"), \
        find("the same, ribbons used freely")
    weekly, block, cycle = find("+ psalms and hymns printed"), find("+ psalmody blocks:"), find("+ Psalter in the order")
    blockh, hymn, psal = find("+ psalmody blocks and hymns"), find("+ hymns of"), find("+ psalms of")
    md = ["## What changed, and proposals", ""]
    if old:
        md += ["### Done: card, whole Compline, ribbons by use (B-14…B-16)", "",
               f"- **Combined:** without the card and with ribbons by section, the book needs {f1(old['search'])} "
               f"look-ups and {old['seconds'] / 60:.1f} min a day. As printed now: {f1(b0['search'])} and "
               f"{b0['seconds'] / 60:.1f} min.",
               "- **Ribbons:** with the same card and Compline, the previous section-by-section scheme needs "
               f"{f1(section['search'])} look-ups, against {f1(b0['search'])} by use. The best possible placement "
               f"(free) would need {f1(free['search'])}.",
               "- **Compline:** whole Compline added 24 pages.", ""]
    md += ["### Proposals (every text kept; ordered by time saved per page added)", ""]
    items = []
    if block:
        items.append((0, "**Psalmody blocks: the Psalter in the order of the four-week cycle, with each hour's "
                      "antiphons beside its psalms.**",
                      [f"Saves {saved(block)} a day; {f1(block['search'])} look-ups, {f1(block['moves'])} moves.",
                       "**No text is added:** the psalms and canticles are reordered (each printed once at its first "
                       "use, later uses referring to it), and the antiphons move from the grid into the Psalter.",
                       "**Nothing is lost:** psalms the cycle does not use (or only partly uses) follow in biblical "
                       "order, so every verse is still printed.",
                       "**Trade-off:** biblical order gives way to the cycle. An index by psalm number and the margin "
                       "notes of uses keep every psalm findable.",
                       "**Effect:** the grid page of an hour keeps the hymn, reading, responsory, intercessions and "
                       "prayer, and the antiphon ↔ psalm turning disappears."]))
    if cycle:
        items.append((0, "**The Psalter in cycle order only (antiphons stay in the grid).**",
                      [f"Saves {saved(cycle)} a day.",
                       "Most of the gain of the psalmody blocks comes from putting the antiphons with the psalms, not "
                       "from the order."]))
    if weekly:
        items.append((weekly["extra_pages"], "**Psalms and hymns printed at each hour of the four-week cycle "
                      "(branch `exp/weekly-psalter`).**",
                      [f"Saves {saved(weekly)} a day; {f1(weekly['search'])} look-ups.",
                       f"Costs about +{weekly['extra_pages']} pages (estimate; the branch measures the real count).",
                       "The Psalter in biblical order stays as it is."]))
    if blockh:
        items.append((blockh["extra_pages"], "**Psalmody blocks + hymns at each hour.**",
                      [f"Saves {saved(blockh)} a day for about +{blockh['extra_pages']} pages.",
                       "A middle way between the first proposal and the weekly psalter."]))
    if hymn and psal:
        items.append((hymn["extra_pages"], "**Hymns alone at each hour.**",
                      [f"Saves only {saved(hymn)} for about +{hymn['extra_pages']} pages.",
                       "Hymns repeat across days, so a ribbon (7) already covers much of their turning.",
                       "Not recommended alone."]))
    items.append((0, "**Thumb-index tabs on the fore-edge**, one per part (Saints, Commons, Ordinary, Proper of "
                  "Time, Hymns, Psalter, Readings), as in many bibles.",
                  ["The counts stay the same, but each look-up starts from the right part of the book.",
                   f"At ~3 s less per look-up: about {b0['search'] * 3 / 60:.1f} min a day.",
                   "No pages added; printed as bleed tabs."]))
    for i, (pp, title, bullets) in enumerate(items, 1):
        md += [f"{i}. {title}"] + [f"   - {b}" for b in bullets] + [""]
    return md


def sample(sim, L, trial_rows) -> list[str]:
    from lh.sim.run import without_card
    names = ribbon_names(SCHEME)
    md = ["## A day step by step", "",
          "One weekday and one memorial, as printed, with the card in hand. Ribbons are by use, starting where "
          "the previous day left them. Every page move and ribbon movement of every simulated day is in "
          "`build/sim/events.jsonl.gz`.", ""]
    picks = [r for r in trial_rows if r["kind"] == "weekday"][:1] + [r for r in trial_rows if r["kind"] == "memorial"][:1]
    for r in picks:
        d = dt.date.fromisoformat(r["date"])
        cel, steps = sim.steps(d)
        steps = without_card(steps)
        prev = without_card(sim.steps(d - dt.timedelta(days=1))[1])
        reader = Reader(L, "roles", scheme=SCHEME)
        reader.day(prev, steps)
        events = reader.day(steps, without_card(sim.steps(d + dt.timedelta(days=1))[1]))
        md += [f"### {sim.cals[False].describe(cel)}", ""]
        rowsx = []
        for s, e in zip(steps, events):
            act = f"ribbon {names[e.ribbon]}" if e.action == "ribbon" else \
                {"stay": "", "turn": "turn", "search": "**look up**"}[e.action]
            lay = f"lay {names[e.laid]}" if e.laid else ""
            rowsx.append([HOUR_NAME.get(s.hour, s.hour), s.slot, short(s.what), L.label(s.page), act, lay])
        md += table(["Hour", "Part", "Text", "Page", "Move", "Ribbon"], rowsx) + [""]
    return md


def short(what: str) -> str:
    if what.startswith(("ord:", "heading")):
        return what
    return what.split(".")[1][:32] if "." in what else what[:32]
