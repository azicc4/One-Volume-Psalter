"""reports/simulation.md: what the simulated readers did, where the time goes, and what would make the book faster to
use. Written by `python -m lh simulate` from the run's own data (build/sim/)."""
from __future__ import annotations

import collections
import datetime as dt
import gzip
import json
import statistics

from lh.config import REPORTS
from lh.sim.reader import COST, RIBBONS, Reader

RIBBON_NAME = {"S": "1 Saints", "C": "2 Commons", "O": "3 Ordinary", "T": "4 Proper of Time", "H": "5 Hymns",
               "P1": "6 Psalter 1", "P2": "7 Psalter 2", "P3": "8 Psalter 3", "P4": "9 Psalter 4", "R": "10 Readings"}
HOUR_NAME = {"INV": "Invitatory", "OR": "Office of Readings", "LAUDS": "Lauds", "MIDDAY": "Daytime Prayer (Sext)",
             "VESPERS": "Vespers", "V1": "First Vespers", "V2": "Second Vespers", "COMPLINE": "Compline",
             "COMPLINE1": "Compline after First Vespers"}


def table(head: list[str], rows: list[list]) -> list[str]:
    out = ["| " + " | ".join(head) + " |", "|" + "|".join("---" if i == 0 else "---:" for i in range(len(head))) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return out


def f1(x):
    return f"{x:.1f}"


def write_report(sim, trial_rows, rows, exp, prof, timing) -> str:
    from lh.sim.run import OUT
    L = sim.L
    md = ["# Simulated use of the book: page turns and ribbons", "",
          f"Generated by `python -m lh simulate` on {dt.date.today().isoformat()} from the book as built "
          f"({L.n:,} pages) and the database. Do not edit: re-run the command.", ""]

    # ------------------------------------------------------------------ method
    md += ["## What was simulated", "",
           "**The reader.** A reader prays the hours of each day from this one volume, using its ten ribbons:",
           "1 Saints, 2 Commons, 3 Ordinary, 4 Proper of Time, 5 Hymns, 6–9 Psalter 1–4, 10 Readings.",
           "",
           "**The hours.** Each day the reader says:",
           "- the Invitatory;",
           "- the Office of Readings;",
           "- Lauds;",
           "- Daytime Prayer (Sext);",
           "- Vespers, which is First Vespers of the next day when that day is a Sunday or a solemnity;",
           "- Compline.",
           "",
           "**Where each text comes from.**",
           "- Every text is taken from the page it is printed on in this book, via the LaTeX labels of the last "
           "build. 1,503 invisible labels at the hour headings give where each hour begins.",
           "- Each hour starts at its heading. Every text is then visited in order: antiphon, psalm, antiphon "
           "again, reading, and so on.",
           "- A memorial takes the weekday's psalms and its own proper texts; anything else comes from its Common.",
           "- Feasts fill gaps from their Common; Lauds and Vespers of a feast use the psalms of Sunday Week I.",
           "",
           "**The calendar** is the General Roman Calendar (`lh/sim/calendar.py`), simplified:",
           "- universal dates (Epiphany on 6 January, Ascension and Corpus Christi on Thursday);",
           "- no transfers;",
           "- obligatory memorials only (optional ones in one variant run);",
           "- memorials in Lent and on 17–24 December are commemorations only.",
           "",
           "**Each change of spread is classified as:**",
           f"- **turn**: to the next or previous spread (~{COST['turn']} s);",
           f"- **ribbon**: opening the book at a ribbon lying in the spread needed (~{COST['ribbon']} s);",
           f"- **look-up**: finding the page by its number (~{COST['search']} s).",
           "",
           f"**Laying a ribbon** costs ~{COST['lay']} s. These times are rough guesses; the counts are the result.",
           "",
           "**Ribbon policies:**",
           "- *by section*: the book's design, each ribbon keeping its section. The reader moves a section's "
           "ribbon to a new place only if that place will be needed again, today or tomorrow, before the old one.",
           "- *free*: any ribbon can go anywhere, placed by the best possible rule (Belady). This is the best ten "
           "ribbons can do.",
           "- *none*: no ribbons at all.",
           "",
           "Ribbons stay where they are from one day to the next.", ""]

    # ------------------------------------------------------------------ timing
    md += ["## Runs and timing", "",
           "**Phase 1 (trial):** 10 random days, timed.",
           f"- {timing['per_day_ms']:.0f} ms per simulated day (all six hours).",
           f"- {timing['init']:.0f} s of setup: the book generator, labels and calendar.",
           "",
           f"**Phase 2:** every day of {timing['years']} consecutive liturgical years, from Advent 2026. "
           "28 years is a full cycle of weekdays against dates.",
           "- Runs: *by section*, *free*, *none*, and *by section* with optional memorials kept.",
           f"- {timing['phase2_days']:,} simulated days in {timing['phase2_min']:.1f} min.",
           "",
           f"**Phase 3:** {len(exp)} layout and ribbon experiments over the same dates, in "
           f"{timing['phase3_min']:.1f} min.",
           "",
           f"**Phase 4:** {len(prof)} reader-profile runs, in {timing['phase4_min']:.1f} min.",
           "",
           f"**Total:** {timing['total_min']:.1f} min of a {timing['budget_min']:.0f}-min budget. Every planned "
           "run finished, so the rest of the budget was not needed.", ""]
    md += ["### Phase 1: the ten trial days (book as printed, ribbons by section)", ""]
    md += table(["Date", "Office", "Kind", "Steps", "Moves", "Look-ups", "Ribbon jumps", "Turns", "Ribbons laid",
                 "Handling"],
                [[r["date"], r["office"], r["kind"], r["steps"], r["moves"], r["search"], r["ribbon"], r["turn"],
                  r["lay"], f"{r['seconds'] / 60:.1f} min"] for r in trial_rows]) + [""]

    # ------------------------------------------------------------------ baseline
    by = collections.defaultdict(list)
    for r in rows:
        if r["tag"] != "trial":
            by[r["tag"]].append(r)
    names = {"roles": "by section (the book's design)", "free": "free (best case for 10 ribbons)",
             "none": "no ribbons", "roles+optional": "by section, optional memorials kept"}
    md += ["## The book as printed", "", "### Per day, by ribbon policy", ""]
    md += table(["Ribbon policy", "Days", "Moves", "Look-ups", "Ribbon jumps", "Turns", "Ribbons laid",
                 "Handling per day"],
                [[names.get(t, t), len(rs), f1(m(rs, "moves")), f1(m(rs, "search")), f1(m(rs, "ribbon")),
                  f1(m(rs, "turn")), f1(m(rs, "lay")), f"{m(rs, 'seconds') / 60:.1f} min"] for t, rs in by.items()])
    base = by["roles"]
    md += ["", "### Per hour (by section)", ""]
    hrs = collections.defaultdict(collections.Counter)
    for r in base:
        for h, c in r["hours"].items():
            hrs[h].update(c)
            hrs[h]["n"] += 1
    md += table(["Hour", "Days said", "Steps", "Moves", "Look-ups", "Ribbon jumps", "Ribbons laid", "Handling"],
                [[HOUR_NAME.get(h, h), c["n"], f1(c["steps"] / c["n"]), f1(c["moves"] / c["n"]),
                  f1(c["search"] / c["n"]), f1(c["ribbon"] / c["n"]), f1(c["lay"] / c["n"]),
                  f"{c['seconds'] / c['n']:.0f} s"]
                 for h, c in sorted(hrs.items(), key=lambda kv: list(HOUR_NAME).index(kv[0]))])
    md += ["", "### By kind of day (by section)", ""]
    kinds = collections.defaultdict(list)
    for r in base:
        kinds[r["kind"]].append(r)
    md += table(["Kind of day", "Days", "Look-ups", "Moves", "Handling"],
                [[k, len(rs), f1(m(rs, "search")), f1(m(rs, "moves")), f"{m(rs, 'seconds') / 60:.1f} min"]
                 for k, rs in sorted(kinds.items(), key=lambda kv: -len(kv[1]))])

    # where the look-ups come from (event log of the baseline)
    ev_path = OUT / "events.jsonl.gz"
    searches, ord_pages = collections.Counter(), collections.Counter()
    jumps, lays = collections.Counter(), collections.Counter()
    with gzip.open(ev_path, "rt", encoding="utf-8") as f:
        for line in f:
            e = json.loads(line)
            if e["tag"] != "roles":
                continue
            if e["action"] == "search":
                h = "VESPERS" if e["hour"] in ("V1", "V2") else "COMPLINE" if e["hour"] == "COMPLINE1" else e["hour"]
                searches[(e["slot"], e["section"])] += 1
                if e["section"] == "The Ordinary":
                    ord_pages[(e["to"], e["slot"])] += 1
            if e["action"] == "ribbon":
                jumps[e["ribbon"]] += 1
            if e.get("laid"):
                lays[e["laid"]] += 1
    n = len(base)
    md += ["", "### Where the look-ups come from (per day)", ""]
    md += table(["Text", "Section", "Look-ups per day"],
                [[slot, sec, f"{c / n:.2f}"] for (slot, sec), c in searches.most_common(16)])
    md += ["", "Ordinary pages looked up most often (per day): " + "; ".join(
        f"p. {p} ({s}) {c / n:.2f}" for (p, s), c in ord_pages.most_common(8)) + ".", ""]
    md += ["### The ribbons (per day)", ""]
    md += table(["Ribbon", "Opened at", "Moved"], [[RIBBON_NAME[r], f"{jumps[r] / n:.2f}", f"{lays[r] / n:.2f}"]
                                                   for r in RIBBONS])

    # ------------------------------------------------------------------ experiments
    b0 = exp[0]
    md += ["", "## What would make it faster: experiments", "",
           f"The same {b0['days']:,} days, with the reader turning through each variant of the book. "
           "Extra pages are estimated: every text that would be printed again in a new place, at the text density "
           "of the section it is printed in now.", ""]
    md += table(["Variant", "Look-ups", "Moves", "Handling per day", "Saved per day", "Saved", "Extra pages"],
                [[e["name"], f1(e["search"]), f1(e["moves"]), f"{e['seconds'] / 60:.1f} min",
                  f"{(b0['seconds'] - e['seconds']) / 60:.1f} min",
                  f"{100 * (b0['seconds'] - e['seconds']) / b0['seconds']:.0f} %", f"+{e['extra_pages']}"]
                 for e in exp])
    if prof:
        md += ["", "### Reader profiles", ""]
        md += table(["Hours prayed", "Layout", "Look-ups", "Moves", "Handling per day"],
                    [[p["profile"], p["layout"], f1(p["search"]), f1(p["moves"]), f"{p['seconds'] / 60:.1f} min"]
                     for p in prof])

    # ------------------------------------------------------------------ recommendations
    get = {e["name"]: e for e in exp}

    def find(prefix):
        return next((e for e in exp if e["name"].startswith(prefix)), None)

    card, comp, both = find("Ordinary card, full"), find("Compline forms"), find("full card + whole Compline")
    split, free = find("two ribbons"), find("ribbons used freely (best")
    hymn, psal, all_ = find("hymns printed"), find("four-week cycle with"), find("full card + Compline + hymns")
    saved = lambda e: (b0["seconds"] - e["seconds"]) / 60
    md += ["", "## Findings", ""]
    if None in (card, comp, both, split, free, hymn, psal, all_):
        md += ["Not every experiment ran within the time budget; re-run with a larger `--budget-min` for the "
               "findings.", ""]
        card = comp = both = split = free = hymn = psal = all_ = None
    if card is not None:
        md += _findings(b0, card, comp, both, split, free, hymn, psal, all_, saved, lays, jumps, n)
    md += _sample(sim, L, trial_rows)
    md += ["## Files", "",
           "- `build/sim/days.jsonl`: one summary per simulated day and run.",
           "- `build/sim/events.jsonl.gz`: every page move and ribbon movement of the baseline runs, as "
           "date, hour, text, from, to, section, action, ribbon, ribbon laid and cost.",
           "- `build/sim/experiments.jsonl` and `build/sim/profiles.jsonl`: the phase 3 and phase 4 results.",
           "- **Code:** `lh/sim/` (calendar, layout, office, reader, whatif, run, report).", ""]
    path = REPORTS / "simulation.md"
    path.write_text("\n".join(md), encoding="utf-8")
    return str(path)


def _findings(b0, card, comp, both, split, free, hymn, psal, all_, saved, lays, jumps, n) -> list[str]:
    md = [f"**1. The Ordinary is the biggest single cost.**",
           "- Its fixed parts are on four different spreads: the opening (p. 674), the Gospel canticles "
           "(pp. 679, 681), the Pater noster and dismissals (pp. 682–683), and the Compline forms (pp. 685–691).",
           f"- The one Ordinary ribbon is moved about {lays['O'] / n:.0f} times a day.",
           f"- A loose **Ordinary card** removes about {b0['search'] - card['search']:.0f} look-ups and "
           f"{b0['moves'] - card['moves']:.0f} moves a day ({saved(card):.1f} min). It costs no pages.",
           "- The card holds the opening verses, Benedictus, Magnificat, Nunc dimittis, Psalm 95, Pater noster, "
           "dismissals, blessing and Te Deum, as many breviaries supply. A ribbon card or the endpapers would "
           "also do.", ""]
    md += [f"**2. Compline should be self-contained.**",
           "- Printing each weekly form whole (its psalm and the parts it shares with other forms) saves "
           f"{saved(comp):.1f} min a day for about +{comp['extra_pages']} pages.",
           f"- With the card: {both['search']:.0f} look-ups and {both['seconds'] / 60:.1f} min a day, against "
           f"{b0['search']:.0f} and {b0['seconds'] / 60:.1f}. That is "
           f"{100 * saved(both) * 60 / b0['seconds']:.0f} % less handling for about +{both['extra_pages']} pages.",
           ""]
    md += [f"**3. The ribbons are assigned by section, not by use.**",
           f"- Ribbons 8–9 (Psalter 3 and 4), 2 (Commons) and 5 (Hymns) are opened fewer than "
           f"{max(jumps[r] for r in ('P3', 'P4', 'C', 'H')) / n:.1f} times a day.",
           f"- Ribbon 4 (Proper of Time) is opened {jumps['T'] / n:.0f} times a day.",
           f"- Used freely, the same ten ribbons would need {free['search']:.0f} look-ups instead of "
           f"{b0['search']:.0f}.",
           f"- A cheap step towards that is giving ribbon 9 to the end of the Ordinary: {split['search']:.0f} "
           "look-ups. Once the card exists, it adds almost nothing.", ""]
    md += [f"**4. Printing the weekly psalter and its hymns in the four-week cycle**, as the four-volume breviary "
           "does, removes most of the antiphon ↔ psalm turning.",
           f"- Psalms: {saved(psal):.1f} min a day for about +{psal['extra_pages']} pages.",
           f"- Hymns: {saved(hymn):.1f} min a day for about +{hymn['extra_pages']} pages.",
           f"- Everything together: {all_['search']:.0f} look-ups and {all_['seconds'] / 60:.1f} min a day, for "
           f"about +{all_['extra_pages']} pages.",
           "- This works against the one-volume goal and the psalter-with-margin-notes design, so it is a trade-off "
           "for the owner rather than a fix.", ""]
    md += ["**5. Looking up each new text once is unavoidable** when every text is printed once: each hour's "
           "psalms, hymn and readings are new pages.",
           "- That floor is about 20 look-ups a day for the full Office, fewer for Lauds, Vespers and Compline "
           "only.", ""]
    return md


def _sample(sim, L, trial_rows) -> list[str]:
    md = ["## A day step by step", "",
           "One weekday and one memorial, as printed, ribbons by section starting where the previous day "
           "left them. Every page move and ribbon movement of every simulated day is in "
           "`build/sim/events.jsonl.gz`.", ""]
    picks = [r for r in trial_rows if r["kind"] == "weekday"][:1] + [r for r in trial_rows if r["kind"] == "memorial"][:1]
    for r in picks:
        d = dt.date.fromisoformat(r["date"])
        cel, steps = sim.steps(d)
        prev = sim.steps(d - dt.timedelta(days=1))[1]
        reader = Reader(L, "roles")
        reader.day(prev, steps)
        events = reader.day(steps, sim.steps(d + dt.timedelta(days=1))[1])
        md += [f"### {sim.cals[False].describe(cel)}", ""]
        rowsx = []
        for s, e in zip(steps, events):
            act = f"ribbon {RIBBON_NAME[e.ribbon]}" if e.action == "ribbon" else \
                {"stay": "", "turn": "turn", "search": "**look up**"}[e.action]
            lay = f"lay {RIBBON_NAME[e.laid]}" if e.laid else ""
            rowsx.append([HOUR_NAME.get(s.hour, s.hour), s.slot, short(s.what), L.label(s.page), act, lay])
        md += table(["Hour", "Part", "Text", "Page", "Move", "Ribbon"], rowsx) + [""]
    return md


def m(rs, k):
    return statistics.mean(r[k] for r in rs)


def short(what: str) -> str:
    if what.startswith(("ord:", "heading")):
        return what
    return what.split(".")[1][:32] if "." in what else what[:32]
