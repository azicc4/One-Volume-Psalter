"""Coverage: prove that every line of a source PDF is in the database (or deliberately excluded).

Round-trip proves that what was parsed is faithful; coverage proves that nothing was skipped. A line of the L1 dump
(build/l1/<KEY>.sqlite) in the parsed page scope counts as covered when it
  * lies inside an hour instance (hour_instance.l1_first … l1_last) and is not part of an `unparsed` element, or
  * is a recorded heading or day preamble (source_line.role = heading | day_extra), or
  * is on a page the source plug-in declares NON_CONTENT (cover, index …, each with a reason).
Everything else is a gap, listed in reports/coverage_<KEY>.md. Gate: 0 gaps.
"""
from __future__ import annotations

import bisect
import collections
import sqlite3

from lh.config import DB_PATH, REPORTS
from lh.extract.spans import open_l1
from lh.sources import non_content


def coverage(source: str, db=DB_PATH) -> dict:
    con = sqlite3.connect(db)
    src = con.execute("SELECT p0, p1, pdf FROM source WHERE key=?", (source,)).fetchone()
    if not src:
        raise SystemExit(f"source {source} is not in the database; run `python -m lh build {source}`")
    p0, p1, pdf = src
    ranges = sorted(con.execute("SELECT l1_first, l1_last FROM hour_instance WHERE source=?", (source,)).fetchall())
    starts = [r[0] for r in ranges]
    recorded = set()
    for a, b in con.execute(
            "SELECT l1_first, l1_last FROM source_line WHERE source=? AND role IN ('heading','day_extra')", (source,)):
        recorded.update(range(a, b + 1))     # a visual line may merge several L1 rows (justified prose, SP 242)
    front = {r[0]: r[1] for r in con.execute("SELECT l1_first, page FROM source_line WHERE source=? AND role='front'", (source,))}
    unparsed = con.execute("""SELECT o.page, o.source_text FROM occurrence o JOIN hour_instance h ON h.id=o.hour_id
                              WHERE h.source=? AND o.type='unparsed'""", (source,)).fetchall()
    con.close()

    def in_hour(i: int) -> bool:
        k = bisect.bisect_right(starts, i) - 1
        return k >= 0 and ranges[k][0] <= i <= ranges[k][1]

    l1 = open_l1(source)
    q = "SELECT id, page, text FROM line" + (" WHERE page BETWEEN ? AND ?" if p0 else "") + " ORDER BY id"
    rows = l1.execute(q, (p0, p1) if p0 else ()).fetchall()
    l1.close()
    total, covered, excluded = len(rows), 0, collections.Counter()
    gaps = []
    for r in rows:
        i, page, text = r["id"], r["page"], r["text"]
        if in_hour(i) or i in recorded:
            covered += 1
            continue
        reason = non_content(source, page)
        if reason:
            excluded[reason] += 1
            continue
        gaps.append((page, text))
    gap_count = len(gaps) + len(unparsed)
    result = {"source": source, "pdf": pdf, "lines": total, "covered": covered, "excluded": dict(excluded),
              "gaps": gap_count, "gap_examples": gaps[:200], "unparsed": [(p, t) for p, t in unparsed[:100]]}
    write_report(result, p0, p1)
    return result


def write_report(r: dict, p0, p1) -> None:
    scope = f"pages {p0}–{p1}" if p0 else "all pages"
    pct = 100.0 * (r["lines"] - r["gaps"] - sum(r["excluded"].values())) / max(1, r["lines"] - sum(r["excluded"].values()))
    L = [f"# Coverage — {r['source']} ({r['pdf']}, {scope})", "",
         "Generated by `python -m lh verify`. Every text line of the source must be in the database (inside an hour, "
         "or a recorded heading / day preamble) unless its page is declared non-content in `lh/sources/`.", "",
         "| | Lines |", "|---|---|",
         f"| Total lines in scope | {r['lines']:,} |",
         f"| In the database | {r['covered']:,} |"]
    L += [f"| Excluded — {k} | {v:,} |" for k, v in r["excluded"].items()]
    L += [f"| **Gaps** (missing or unparsed) | **{r['gaps']:,}** |", "", f"Coverage of content lines: **{pct:.2f}%**", ""]
    if r["gap_examples"]:
        L += ["## Lines not in the database", "", "| Page | Text |", "|---|---|"]
        L += [f"| {p} | {t[:120].replace('|', '/')} |" for p, t in r["gap_examples"]]
        L.append("")
    if r["unparsed"]:
        L += ["## Unparsed elements (inside hours)", "", "| Page | Text |", "|---|---|"]
        L += [f"| {p} | {t[:120].replace('|', '/')} |" for p, t in r["unparsed"]]
    REPORTS.mkdir(exist_ok=True)
    (REPORTS / f"coverage_{r['source']}.md").write_text("\n".join(L) + "\n", encoding="utf-8")
