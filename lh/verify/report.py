"""Write reports/verification.md from the check results."""
from __future__ import annotations

import json
import sqlite3

from lh.config import DB_PATH, REPORTS
from lh.model.canon import plain


def write_report(out: dict, db=DB_PATH) -> str:
    con = sqlite3.connect(db)
    con.row_factory = sqlite3.Row
    n_obj = con.execute("SELECT count(*) FROM object").fetchone()[0]
    n_occ = con.execute("SELECT count(*) FROM occurrence WHERE object_id IS NOT NULL").fetchone()[0]
    by_type = con.execute("SELECT type, count(*) n, sum(n_occ) occ FROM object GROUP BY type ORDER BY occ DESC").fetchall()
    srcs = con.execute("SELECT key, pdf, pages FROM source").fetchall()
    rt, st, ps, va = out["roundtrip"], out["structure"], out["psalms"], out["variants"]
    L = ["# Verification report", "",
         "Generated by `python -m lh verify`. Sources: " + ", ".join(f"`{s['pdf']}` ({s['pages']} pp.)" for s in srcs), "",
         "## Summary", "",
         "| Check | Result |", "|---|---|",
         f"| Round-trip (object + occurrence data reproduces every printed text) | {'PASS' if not rt['failures'] else 'FAIL'}: {rt['occurrences'] - rt['failures']}/{rt['occurrences']} |"]
    for k, v in out.items():
        if k.startswith("index:"):
            L.append(f"| PDF index ({k[6:]}): parsed hours match the PDF's own index | "
                     f"{'PASS' if not v['n_mismatch'] else 'FAIL'}: {v['days_in_index'] - v['n_mismatch']}/{v['days_in_index']} days |")
        if k.startswith("coverage:"):
            excl = sum(v["excluded"].values())
            L.append(f"| Coverage ({k[9:]}): every source line is in the database (`reports/coverage_{k[9:]}.md`) | "
                     f"{'PASS' if not v['gaps'] else 'FAIL'}: {v['lines'] - excl - v['gaps']:,}/{v['lines'] - excl:,} "
                     f"content lines; {v['gaps']} gap(s); {excl:,} non-content lines excluded |")
    if rt.get("overridden"):
        L.append(f"| Overrides applied (`data/overrides/`, skipped by round-trip) | {rt['overridden']} occurrences |")
    L += [f"| Structure (every hour has its GILH-required slots) | {'PASS' if not st['incomplete'] else 'FAIL'}: {st['hours'] - st['incomplete']}/{st['hours']} hours"
          + (f" ({st['excused']} with source omissions excused by the plug-ins' STRUCTURE_EXCEPTIONS)" if st.get("excused") else "")
          + " |",
          f"| Psalm text consensus (every printing of a verse line agrees) | {ps['lines'] - ps['divergent']}/{ps['lines']} lines unanimous; {ps['divergent']} lines need review |",
          f"| Near-duplicate texts (possible source typos/variants) | {va['pairs']} pairs to review |", "",
          f"Database: **{n_occ:,} printed occurrences → {n_obj:,} canonical objects.**", "",
          "| Object type | Distinct objects | Printed occurrences |", "|---|---|---|"]
    L += [f"| {r['type']} | {r['n']:,} | {r['occ']:,} |" for r in by_type]
    if ps["examples"]:
        L += ["", "## Psalm lines with divergent readings", "",
              "The majority reading is used for the book; minority readings are listed with their printing counts.", "",
              "| Psalm | Verse | Line | Readings (count) |", "|---|---|---|---|"]
        for r in con.execute("SELECT subject, detail FROM check_result WHERE check_name='psalms' AND status='flag'"):
            d = json.loads(r["detail"])["readings"]
            ps_, rest = r["subject"].split(":", 1)
            L.append(f"| {ps_} | {rest.split(' ')[0]} | {rest.split('line ')[1]} | " +
                     "<br>".join(f"{plain(t)} ({n})" for t, n in sorted(d.items(), key=lambda kv: -kv[1])) + " |")
    if va["examples"]:
        L += ["", "## Near-duplicate objects (review)", "",
              "Pairs of distinct objects whose texts differ only slightly. Most are genuine differences "
              "(e.g. *Regem* vs *Deum magnum*); some are punctuation inconsistencies in the source.", "",
              "| Type | Object A (printings) | Object B (printings) | Similarity |", "|---|---|---|---|"]
        for r in con.execute("SELECT subject, detail FROM check_result WHERE check_name='variants'"):
            d = json.loads(r["detail"])
            a, b = r["subject"].split(" ~ ")
            ta = con.execute("SELECT plain FROM object WHERE id=?", (a,)).fetchone()[0]
            tb = con.execute("SELECT plain FROM object WHERE id=?", (b,)).fetchone()[0]
            L.append(f"| {d['type']} | {ta[:90]} ({d['n'][0]}) | {tb[:90]} ({d['n'][1]}) | {d['score']} |")
    con.close()
    REPORTS.mkdir(exist_ok=True)
    path = REPORTS / "verification.md"
    path.write_text("\n".join(L) + "\n", encoding="utf-8")
    return str(path)
